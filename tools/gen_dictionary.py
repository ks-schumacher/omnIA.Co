#!/usr/bin/env python3
"""Generate src/engine/dicom/dictionary.js from the pydicom data dictionary.

The DICOM data dictionary (PS3.6) is a public standard; pydicom (MIT license)
distributes it in machine-readable form. Command elements (group 0000) are
omitted. Output format: one entry per line, "GGGGEEEE VR Keyword".
"""
import sys
from pydicom._dicom_dict import DicomDictionary, RepeatersDictionary
import pydicom

lines = []
for tag, (vr, vm, name, retired, keyword) in sorted(DicomDictionary.items()):
    if (tag >> 16) == 0x0000:
        continue
    lines.append(f"{tag:08X} {vr.replace(' or ', '|')} {keyword or '-'}")
reps = []
for mask, (vr, vm, name, retired, keyword) in sorted(RepeatersDictionary.items()):
    reps.append(f"{mask.upper()} {vr.replace(' or ', '|')} {keyword or '-'}")

out = sys.argv[1]
with open(out, "w", encoding="utf-8") as f:
    f.write("// AUTO-GENERATED by tools/gen_dictionary.py from the DICOM PS3.6 data dictionary\n")
    f.write(f"// as distributed by pydicom {pydicom.__version__} (MIT license). Do not edit by hand.\n")
    f.write("export const DICT_TEXT = `\n" + "\n".join(lines) + "\n`;\n")
    f.write("export const REPEATERS_TEXT = `\n" + "\n".join(reps) + "\n`;\n")
print(len(lines), "entries,", len(reps), "repeaters")
